USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS PRODUCT_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS PRODUCT_CATALOG;

CREATE SCHEMA IF NOT EXISTS PRODUCT_CATALOG.RAW;
CREATE SCHEMA IF NOT EXISTS PRODUCT_CATALOG.STAGING;
CREATE SCHEMA IF NOT EXISTS PRODUCT_CATALOG.SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS PRODUCT_CATALOG.CORE;

CREATE STAGE IF NOT EXISTS PRODUCT_CATALOG.RAW.PRODUCT_STAGE;

CREATE FILE FORMAT IF NOT EXISTS PRODUCT_CATALOG.RAW.CSV_FMT
    TYPE = CSV
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    SKIP_HEADER = 1
    ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE TABLE IF NOT EXISTS RAW.RAW_PRODUCTS (
    PRODUCT_ID VARCHAR,
    NAME VARCHAR,
    BRAND VARCHAR,
    CATEGORY VARCHAR,
    SUB_CATEGORY VARCHAR,
    PRICE VARCHAR,
    LIST_PRICE VARCHAR,
    DISCOUNT_PCT VARCHAR,
    AVERAGE_RATING VARCHAR,
    OUT_OF_STOCK VARCHAR,
    DESCRIPTION VARCHAR,
    SELLER VARCHAR,
    PRODUCT_URL VARCHAR,
    SOURCE_CRAWLED_AT VARCHAR,
    SOURCE_FILE VARCHAR,
    BATCH_ID VARCHAR,
    LOADED_AT TIMESTAMP_NTZ
);